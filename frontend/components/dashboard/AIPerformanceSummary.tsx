"use client";

import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/Card";
import { Skeleton } from "@/components/ui/Skeleton";
import { cn } from "@/lib/utils";

interface AIPerformanceSummaryProps {
  data: {
    aiClassifiedTickets: number;
    totalTickets: number;
    aiAssistedResponses: number;
    humanApprovalRate: number;
    aiResponseAcceptanceRate: number;
    avgConfidence: number;
  } | null;
  loading?: boolean;
}

export function AIPerformanceSummary({ data, loading }: AIPerformanceSummaryProps) {
  if (loading) {
    return (
      <Card>
        <CardHeader>
          <CardTitle>AI Performance Summary</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="grid grid-cols-2 gap-4">
            <Skeleton className="h-24" />
            <Skeleton className="h-24" />
            <Skeleton className="h-24" />
            <Skeleton className="h-24" />
          </div>
        </CardContent>
      </Card>
    );
  }

  if (!data) {
    return (
      <Card>
        <CardHeader>
          <CardTitle>AI Performance Summary</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="h-32 flex items-center justify-center text-muted-foreground">
            No AI performance data available
          </div>
        </CardContent>
      </Card>
    );
  }

  const aiClassificationRate = data.totalTickets > 0
    ? (data.aiClassifiedTickets / data.totalTickets) * 100
    : 0;

  const metrics = [
    {
      label: "AI Classification Rate",
      value: `${aiClassificationRate.toFixed(1)}%`,
      description: `${data.aiClassifiedTickets} of ${data.totalTickets} tickets`,
      icon: (
        <svg className="h-5 w-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
          <circle cx="12" cy="12" r="10" />
          <path d="M12 6v6l4 2" />
        </svg>
      ),
      color: "primary",
    },
    {
      label: "AI-Assisted Responses",
      value: data.aiAssistedResponses.toLocaleString(),
      description: "Responses generated by AI",
      icon: (
        <svg className="h-5 w-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
          <path d="M12 17v4M9 10h.01M15 10h.01M9 14h.01M15 14h.01" />
          <path d="M21 11.08V12a10 10 0 1 1-5.93-9.14" />
          <polyline points="22 4 12 14.01 9 11.01" />
        </svg>
      ),
      color: "secondary",
    },
    {
      label: "Human Approval Rate",
      value: `${data.humanApprovalRate.toFixed(1)}%`,
      description: "AI responses approved by agents",
      icon: (
        <svg className="h-5 w-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
          <path d="M22 11.08V12a10 10 0 1 1-5.93-9.14" />
          <polyline points="22 4 12 14.01 9 11.01" />
        </svg>
      ),
      color: "success",
    },
    {
      label: "AI Acceptance Rate",
      value: `${data.aiResponseAcceptanceRate.toFixed(1)}%`,
      description: "Approved responses sent to customers",
      icon: (
        <svg className="h-5 w-5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
          <polyline points="20 6 9 17 4 12" />
        </svg>
      ),
      color: "warning",
    },
  ];

  const iconColors = {
    primary: "bg-primary/10 text-primary",
    secondary: "bg-secondary/10 text-secondary",
    success: "bg-success/10 text-success",
    warning: "bg-warning/10 text-warning",
    danger: "bg-danger/10 text-danger",
  };

  return (
    <Card>
      <CardHeader>
        <CardTitle>AI Performance Summary</CardTitle>
      </CardHeader>
      <CardContent>
        <div className="grid grid-cols-2 gap-4">
          {metrics.map((metric) => (
            <div
              key={metric.label}
              className="p-4 rounded-xl bg-muted/50 border border-card-border hover:border-primary/50 transition-colors"
            >
              <div className="flex items-start gap-3">
                <div className={cn("flex-shrink-0 h-10 w-10 rounded-lg flex items-center justify-center", iconColors[metric.color as keyof typeof iconColors])}>
                  {metric.icon}
                </div>
                <div className="flex-1 min-w-0">
                  <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider">{metric.label}</p>
                  <p className="mt-1 text-2xl font-bold text-foreground">{metric.value}</p>
                  <p className="mt-1 text-xs text-muted-foreground">{metric.description}</p>
                </div>
              </div>
            </div>
          ))}
        </div>

        {/* Additional metrics row */}
        <div className="mt-4 grid grid-cols-2 gap-4 text-center">
          <div className="p-4 rounded-xl bg-muted/50 border border-card-border">
            <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider">Avg AI Confidence</p>
            <p className="mt-1 text-2xl font-bold text-foreground">{(data.avgConfidence * 100).toFixed(0)}%</p>
          </div>
          <div className="p-4 rounded-xl bg-muted/50 border border-card-border">
            <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider">Total Tickets Processed</p>
            <p className="mt-1 text-2xl font-bold text-foreground">{data.totalTickets.toLocaleString()}</p>
          </div>
        </div>
      </CardContent>
    </Card>
  );
}